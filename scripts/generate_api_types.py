"""Generate the desktop response types from Pydantic, without a second schema."""
import argparse
import json
from pathlib import Path

from engine.contracts.api import API_MODELS

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'desktop/src/generated/api.ts'


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'], ensure_ascii=False)
    if 'enum' in schema:
        return ' | '.join(json.dumps(value, ensure_ascii=False) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(option) for option in schema['anyOf'])
    kind = schema.get('type')
    if kind == 'array':
        return f"Array<{ts_type(schema['items'])}>"
    if kind == 'object':
        value = schema.get('additionalProperties', True)
        return f"Record<string, {ts_type(value) if isinstance(value, dict) else 'unknown'}>"
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def render_types():
    schemas = {}
    for model in API_MODELS:
        schema = model.model_json_schema(mode='serialization')
        schemas.update(schema.pop('$defs', {}))
        schemas[model.__name__] = schema
    lines = ['// Generated by python scripts/generate_api_types.py. Do not edit by hand.', '']
    for name, schema in sorted(schemas.items()):
        lines.extend(['// prettier-ignore', f'export interface {name} {{'])
        for key, value in schema.get('properties', {}).items():
            # Responses serialize defaults; nullable non-required fields remain optional for compatibility.
            optional = '?' if key not in schema.get('required', []) and value.get('default', False) is None else ''
            lines.append(f'  {key}{optional}: {ts_type(value)};')
        if schema.get('additionalProperties') is True:
            lines.append('  [key: string]: unknown;')
        lines.extend(['}', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render_types()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != content:
            parser.exit(1, 'API types are outdated. Run python scripts/generate_api_types.py\n')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(content, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
